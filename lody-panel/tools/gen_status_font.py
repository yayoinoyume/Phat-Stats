#!/usr/bin/env python3
"""Generate the 56x56 1-bit status glyph header for Lody Panel.

Only the 12 characters used by the panel are included. The font is resolved
through fontconfig (Noto Sans CJK SC Bold) and rendered with ImageMagick, so
the header can be regenerated on any machine with those two tools.

Usage:
    python3 lody-panel/tools/gen_status_font.py

Output:
    lody-panel/firmware/LodyPanel/status_font.h
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path

CHARS = "在跑等你完成空闲出错断线"
SIZE = 56
THRESHOLD = "50%"
FONT_QUERY = "Noto Sans CJK SC:style=Bold"
OUTPUT = Path(__file__).resolve().parent.parent / "firmware" / "LodyPanel" / "status_font.h"


def run(command: list[str]) -> str:
    return subprocess.check_output(command, text=True)


def resolve_font() -> tuple[Path, int, str]:
    raw = run(
        [
            "fc-match",
            "-f",
            "%{file}\n%{index}\n%{family}\n%{style}\n",
            FONT_QUERY,
        ]
    ).splitlines()
    if len(raw) < 4:
        raise SystemExit("fc-match did not return file/index/family/style")
    path = Path(raw[0].strip())
    index = int(raw[1].strip())
    family = raw[2].strip()
    style = raw[3].strip()
    if path.name != "NotoSansCJK-Bold.ttc" or "noto-cjk" not in str(path):
        raise SystemExit(f"unexpected font file: {path}")
    if family != "Noto Sans CJK SC" or style != "Bold":
        raise SystemExit(f"unexpected face: {family} {style}")
    if not path.is_file():
        raise SystemExit(f"font file missing: {path}")
    return path, index, f"{family} {style}"


def resolve_magick_alias(path: Path, index: int) -> str:
    listing = run(["magick", "-list", "font"])
    for block in re.split(r"\n\s*Font:\s*", listing)[1:]:
        lines = block.splitlines()
        if not lines:
            continue
        alias = lines[0].strip()
        fields = dict(
            (key.strip(), value.strip())
            for key, value in re.findall(r"^\s*(\w+):\s*(.*)$", block, re.MULTILINE)
        )
        glyphs = fields.get("glyphs", "")
        if (
            glyphs
            and Path(glyphs).resolve() == path.resolve()
            and fields.get("index") == str(index)
            and fields.get("weight") == "700"
        ):
            return alias
    raise SystemExit(
        "ImageMagick has no alias for "
        f"{path} (index {index}); check 'magick -list font'"
    )


def render(ch: str, alias: str) -> bytes:
    common = [
        "magick",
        "-background",
        "black",
        "-fill",
        "white",
        "-font",
        alias,
        "-pointsize",
        str(SIZE),
        f"label:{ch}",
        "-trim",
        "+repage",
    ]
    width, height = (
        int(value)
        for value in run(common + ["-format", "%w %h", "info:"]).split()
    )
    if width > SIZE or height > SIZE:
        raise SystemExit(
            f"glyph {ch!r} is {width}x{height}, larger than {SIZE}x{SIZE}; "
            "lower the point size deliberately instead of clipping"
        )
    raw = subprocess.check_output(
        common
        + [
            "-gravity",
            "center",
            "-background",
            "black",
            "-extent",
            f"{SIZE}x{SIZE}",
            "-threshold",
            THRESHOLD,
            "-depth",
            "8",
            "gray:-",
        ]
    )
    if len(raw) != SIZE * SIZE:
        raise SystemExit(f"glyph {ch!r}: expected {SIZE * SIZE} bytes, got {len(raw)}")
    if not any(raw):
        raise SystemExit(f"glyph {ch!r} rendered empty")
    return raw


def pack(raw: bytes) -> bytes:
    stride = (SIZE + 7) // 8
    packed = bytearray(stride * SIZE)
    for y in range(SIZE):
        for x in range(SIZE):
            if raw[y * SIZE + x] >= 128:
                packed[y * stride + (x // 8)] |= 0x80 >> (x % 8)
    return bytes(packed)


def main() -> int:
    font_path, font_index, face = resolve_font()
    alias = resolve_magick_alias(font_path, font_index)
    digest = hashlib.sha256(font_path.read_bytes()).hexdigest()
    stride = (SIZE + 7) // 8

    glyphs = [(ch, pack(render(ch, alias))) for ch in CHARS]

    lines = [
        "// Generated by lody-panel/tools/gen_status_font.py; do not edit by hand.",
        f"// Font: {face} ({font_path}, TTC index {font_index})",
        f"// Size: {SIZE}x{SIZE}, 1-bit, row-major, {stride} bytes per row, MSB first.",
        f"// Font SHA-256: {digest}",
        "// Regenerate: python3 lody-panel/tools/gen_status_font.py",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "#include <stdint.h>",
        "",
        f"constexpr uint8_t STATUS_GLYPH_W = {SIZE};",
        f"constexpr uint8_t STATUS_GLYPH_H = {SIZE};",
        f"constexpr uint8_t STATUS_GLYPH_STRIDE = {stride};",
        f"constexpr uint16_t STATUS_GLYPH_BYTES = {stride * SIZE};",
        f"constexpr uint8_t STATUS_GLYPH_COUNT = {len(glyphs)};",
        "",
        "const uint8_t STATUS_GLYPHS[STATUS_GLYPH_COUNT][STATUS_GLYPH_BYTES] PROGMEM = {",
    ]
    for ch, bitmap in glyphs:
        lines.append(f"  {{  // {ch}")
        for y in range(SIZE):
            row = bitmap[y * stride : (y + 1) * stride]
            lines.append("      " + ", ".join(f"0x{byte:02X}" for byte in row) + ",")
        lines.append("  },")
    lines.append("};")
    lines.append("")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(glyphs)} glyphs, {OUTPUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
